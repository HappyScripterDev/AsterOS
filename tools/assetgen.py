#!/usr/bin/env python3
"""Generate branding assets from assets/Logo/Logo.png.

Outputs:
  assets/branding/logo_color.bin   32-bit 0xAARRGGBB pixels (cropped)
  assets/branding/logo_mask.bin    8-bit alpha mask for tinted menu-bar mark
  user/asterdesk/src/logo_data.rs  dimensions + include_bytes!

Run after replacing the logo. Requires Pillow (host only).
"""

from __future__ import annotations

import struct
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "Logo" / "Logo.png"
OUT = ROOT / "assets" / "branding"
RUST = ROOT / "user" / "asterdesk" / "src" / "logo_data.rs"


def main() -> None:
    image = Image.open(SOURCE).convert("RGBA")
    bbox = image.getbbox()
    if bbox is None:
        raise SystemExit("logo is fully transparent")
    image = image.crop(bbox)
    OUT.mkdir(parents=True, exist_ok=True)

    # Full-colour mark, up to 512 px wide, preserving aspect ratio.
    color_width = 512
    color_height = max(1, round(image.height * color_width / image.width))
    color = image.resize((color_width, color_height), Image.LANCZOS)
    pixels = bytearray()
    for y in range(color_height):
        for x in range(color_width):
            r, g, b, a = color.getpixel((x, y))
            pixels += bytes((r, g, b, a))
    (OUT / "logo_color.bin").write_bytes(bytes(pixels))

    # Coverage mask for a tinted menu-bar mark.
    mask_width = 192
    mask_height = max(1, round(image.height * mask_width / image.width))
    alpha = image.getchannel("A").resize((mask_width, mask_height), Image.LANCZOS)
    (OUT / "logo_mask.bin").write_bytes(alpha.tobytes())

    RUST.write_text(
        "\n".join(
            [
                "// @generated by tools/assetgen.py from assets/Logo/Logo.png.",
                "// Do not edit by hand.",
                "",
                f"pub const COLOR_WIDTH: i32 = {color_width};",
                f"pub const COLOR_HEIGHT: i32 = {color_height};",
                f"pub const MASK_WIDTH: i32 = {mask_width};",
                f"pub const MASK_HEIGHT: i32 = {mask_height};",
                "",
                'pub static COLOR: &[u8] = include_bytes!("../../../assets/branding/logo_color.bin");',
                'pub static MASK: &[u8] = include_bytes!("../../../assets/branding/logo_mask.bin");',
                "",
            ]
        )
    )
    print(f"logo color: {color_width}x{color_height} -> {OUT / 'logo_color.bin'}")
    print(f"logo mask:  {mask_width}x{mask_height} -> {OUT / 'logo_mask.bin'}")
    print(f"rust:       {RUST}")


if __name__ == "__main__":
    main()
