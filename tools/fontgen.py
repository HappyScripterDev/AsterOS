#!/usr/bin/env python3
"""Generate the Aster Desktop font atlas from the Inter variable font.

Outputs:
  assets/fonts/atlas.bin         8-bit alpha coverage atlas
  user/asterdesk/src/font_data.rs  generated glyph and face tables

The font is Inter (SIL Open Font License 1.1), downloaded into assets/fonts.
Host-only tool: the OS ships only the rasterized atlas, not a font engine.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts"
FONT_PATH = FONT_DIR / "Inter-Variable.ttf"
MONO_PATH = FONT_DIR / "JetBrainsMono-Variable.ttf"
ATLAS_PATH = FONT_DIR / "atlas.bin"
RUST_PATH = ROOT / "user" / "asterdesk" / "src" / "font_data.rs"
URL = "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/Inter%5Bopsz,wght%5D.ttf"
MONO_URL = "https://raw.githubusercontent.com/google/fonts/main/ofl/jetbrainsmono/JetBrainsMono%5Bwght%5D.ttf"

# name, pixel size, weight, line height
FACES = [
    ("caption", 11, 500, 14, "inter"),
    ("small", 12, 500, 16, "inter"),
    ("body", 13, 400, 18, "inter"),
    ("body_medium", 13, 600, 18, "inter"),
    ("title", 15, 600, 20, "inter"),
    ("headline", 22, 600, 28, "inter"),
    ("display", 28, 600, 34, "inter"),
    ("mono", 13, 400, 18, "mono"),
]

FIRST = 32
LAST = 126


def ensure_font() -> None:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    import urllib.request

    for path, url in ((FONT_PATH, URL), (MONO_PATH, MONO_URL)):
        if path.exists() and path.stat().st_size > 100_000:
            continue
        print(f"downloading {url}")
        urllib.request.urlretrieve(url, path)
        print(f"saved {path} ({path.stat().st_size} bytes)")


def main() -> None:
    ensure_font()
    atlas = bytearray()
    glyphs = []
    faces = []
    for name, size, weight, line, family in FACES:
        path = MONO_PATH if family == "mono" else FONT_PATH
        font = ImageFont.truetype(str(path), size)
        axes = font.get_variation_axes()
        weight_index = 0
        for index, axis in enumerate(axes):
            axis_name = axis.get("name", b"")
            if isinstance(axis_name, bytes):
                axis_name = axis_name.decode(errors="replace")
            if "weight" in axis_name.lower() or "wght" in axis_name.lower():
                weight_index = index
        values = [axis.get("default", axis.get("minimum", 0)) for axis in axes]
        if axes:
            values[weight_index] = weight
            font.set_variation_by_axes(values)
        ascent, descent = font.getmetrics()
        baseline = ascent + max(0, (line - (ascent + descent)) // 2)
        first_glyph = len(glyphs)
        for codepoint in range(FIRST, LAST + 1):
            ch = chr(codepoint)
            advance = int(round(font.getlength(ch)))
            bbox = font.getbbox(ch)
            left, top, right, bottom = bbox
            width = max(0, right - left)
            height = max(0, bottom - top)
            if width == 0 or height == 0:
                glyphs.append((0, 0, 0, 0, max(0, advance), len(atlas)))
                continue
            image = Image.new("L", (width, height), 0)
            draw = ImageDraw.Draw(image)
            draw.text((-left, -top), ch, font=font, fill=255)
            data = image.tobytes()
            if len(data) != width * height:
                raise RuntimeError(f"unexpected bitmap size for {ch!r}")
            offset = len(atlas)
            atlas += data
            glyphs.append((left, top - baseline, width, height, max(0, advance), offset))
        faces.append((size, line, baseline, first_glyph, LAST - FIRST + 1))
        print(f"face {name}: {size}px weight {weight}, {len(atlas)} atlas bytes")

    ATLAS_PATH.write_bytes(bytes(atlas))
    print(f"atlas: {ATLAS_PATH} ({len(atlas)} bytes)")

    lines = [
        "// @generated by tools/fontgen.py - do not edit by hand.",
        "// Inter is licensed under the SIL Open Font License 1.1.",
        "",
        "#[derive(Clone, Copy)]",
        "pub struct Glyph {",
        "    pub xoff: i8,",
        "    pub yoff: i8,",
        "    pub w: u8,",
        "    pub h: u8,",
        "    pub advance: u8,",
        "    pub offset: u32,",
        "}",
        "",
        "#[derive(Clone, Copy)]",
        "pub struct Face {",
        "    pub px: u8,",
        "    pub line: u8,",
        "    pub baseline: u8,",
        "    pub first: u16,",
        "    pub count: u16,",
        "}",
        "",
        f"pub const FIRST: u32 = {FIRST};",
        f"pub const LAST: u32 = {LAST};",
        "",
        f"pub static FACES: [Face; {len(faces)}] = [",
    ]
    for size, line, baseline, first, count in faces:
        lines.append(
            f"    Face {{ px: {size}, line: {line}, baseline: {baseline}, first: {first}, count: {count} }},"
        )
    lines += ["];", "", f"pub static GLYPHS: [Glyph; {len(glyphs)}] = ["]
    for xoff, yoff, w, h, advance, offset in glyphs:
        lines.append(
            f"    Glyph {{ xoff: {xoff}, yoff: {yoff}, w: {w}, h: {h}, advance: {advance}, offset: {offset} }},"
        )
    lines += [
        "];",
        "",
        'pub static ATLAS: &[u8] = include_bytes!("../../../assets/fonts/atlas.bin");',
        "",
        "pub const CAPTION: usize = 0;",
        "pub const SMALL: usize = 1;",
        "pub const BODY: usize = 2;",
        "pub const BODY_MEDIUM: usize = 3;",
        "pub const TITLE: usize = 4;",
        "pub const HEADLINE: usize = 5;",
        "pub const DISPLAY: usize = 6;",
        "pub const MONO: usize = 7;",
        "",
    ]
    RUST_PATH.write_text("\n".join(lines))
    print(f"rust: {RUST_PATH} ({len(glyphs)} glyphs)")


if __name__ == "__main__":
    main()
